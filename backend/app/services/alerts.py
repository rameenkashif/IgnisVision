"""Alerts are stored with a message key + params so each viewer reads them in their own
language (HANDOFF §5). Never generated by an LLM (HANDOFF §10)."""

import uuid
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from app.events.bus import bus, incident_channel
from app.models import Alert
from app.schemas.incidents import AlertOut


async def create_alert(
    db: AsyncSession,
    *,
    incident_id: uuid.UUID,
    severity: str,
    type: str,
    message_key: str,
    params: dict[str, Any] | None = None,
    zone_id: uuid.UUID | None = None,
    commit: bool = True,
) -> Alert:
    alert = Alert(
        incident_id=incident_id,
        zone_id=zone_id,
        severity=severity,
        type=type,
        message_key=message_key,
        message_params=params or {},
    )
    db.add(alert)
    await db.flush()
    await db.refresh(alert)
    if commit:
        await db.commit()
        await publish_alert(alert)
    return alert


async def publish_alert(alert: Alert) -> None:
    await bus.publish(
        incident_channel(alert.incident_id),
        {"type": "alert.created", "alert": AlertOut.model_validate(alert).model_dump(mode="json")},
    )
